        # ── File sharing ──────────────────────────────────────────────────────

        def _safe_filename(raw: str) -> str | None:
            name = str(raw).strip()
            # Clients may submit a full/relative path (e.g. "../nested.txt");
            # only the final path component is ever used as the stored name.
            name = os.path.basename(name.replace("\\", "/"))
            if not name or name in {".", ".."}:
                return None
            if not re.fullmatch(r"[A-Za-z0-9._ -]{1,255}", name):
                return None
            return name

        def _upload_path(name: str) -> Path | None:
            """Resolve one regular file directly below the upload root."""
            root = self._uploads_dir.resolve()
            candidate = (root / name).resolve()
            if candidate.parent != root or root not in candidate.parents:
                return None
            return candidate

        if _UPLOAD_OK:
            @app.post("/api/upload")
            async def upload_file(req: Request, file: UploadFile = FastAPIFile(...)):
                if not _auth(req):
                    return JSONResponse({"error": "Unauthorized"}, status_code=401)

                safe = _safe_filename(file.filename or "upload")
                if safe is None:
                    return JSONResponse({"error": "Invalid file name"}, status_code=400)
                dest = _upload_path(safe)
                if dest is None:
                    return JSONResponse({"error": "Invalid file name"}, status_code=400)
                stem, suffix = Path(safe).stem, Path(safe).suffix
                counter = 1
                while os.path.lexists(dest):
                    safe = f"{stem}_{counter}{suffix}"
                    dest = _upload_path(safe)
                    counter += 1
                    if dest is None:
                        return JSONResponse({"error": "Invalid file name"}, status_code=400)

                size = 0
                max_bytes = MAX_UPLOAD_MB * 1024 * 1024
                tmp_path: Path | None = None
                try:
                    fd, tmp_name = tempfile.mkstemp(prefix=".jarvis-upload-", dir=str(self._uploads_dir))
                    tmp_path = Path(tmp_name)
                    with os.fdopen(fd, "wb") as fout:
                        while True:
                            chunk = await file.read(65536)
                            if not chunk:
                                break
                            size += len(chunk)
                            if size > max_bytes:
                                return JSONResponse(
                                    {"error": f"File too large (max {MAX_UPLOAD_MB} MB)"},
                                    status_code=413,
                                )
                            fout.write(chunk)
                        fout.flush()
                        os.fsync(fout.fileno())
                    # replace cannot follow a destination symlink; it replaces
                    # the directory entry, keeping writes inside the root.
                    os.replace(tmp_path, dest)
                    tmp_path = None
                except Exception:
                    return JSONResponse({"error": "Could not save upload"}, status_code=500)
                finally:
                    if tmp_path is not None:
                        try:
                            tmp_path.unlink(missing_ok=True)
                        except OSError:
                            pass

                asyncio.create_task(self.broadcast({
                    "type": "file_received",
                    "name": dest.name,
                    "size": size,
                }))
                return JSONResponse({"ok": True, "name": dest.name, "size": size})
        else:
            @app.post("/api/upload")
            async def upload_unavailable(req: Request):
                return JSONResponse(
                    {"error": "File uploads require: pip install python-multipart"},
                    status_code=503,
                )

        @app.get("/api/files")
        async def list_files(req: Request):
            if not _auth(req):
                return JSONResponse({"error": "Unauthorized"}, status_code=401)
            files = []
            try:
                root = self._uploads_dir.resolve()
                for f in sorted(
                    (p for p in self._uploads_dir.iterdir()
                     if p.is_file() and not p.is_symlink() and p.resolve().parent == root),
                    key=lambda p: p.stat().st_mtime,
                    reverse=True,
                ):
                    files.append({"name": f.name, "size": f.stat().st_size})
            except Exception:
                pass
            return JSONResponse({"files": files})

        @app.get("/uploads/{filename}")
        async def download_file(filename: str, token: str = ""):
            # Auth via query param — browser <a download> can't send custom headers
            tok = token.strip()
            if not self._valid_token(tok):
                return JSONResponse({"error": "Unauthorized"}, status_code=401)
            safe = _safe_filename(filename)
            if safe is None:
                return JSONResponse({"error": "Not found"}, status_code=404)
            root = self._uploads_dir.resolve()
